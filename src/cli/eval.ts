/** Single-agent baseline vs planner/worker on every labelled document, same budgets. Writes evidence/. */
import { writeFileSync, appendFileSync } from "node:fs";
import { BUDGETS, heldOutTable, runEval, summaryTable, type Summary } from "../evaluate.ts";
import { MissingApiKeyError } from "../extract.ts";
import { RunLog } from "../log.ts";
import { arg, sessionRecord, stamp, startEvidence } from "./common.ts";

const argv = process.argv.slice(2);
const mode = argv.includes("--live") ? "live" : "fixture";
if (mode === "live" && !process.env.ANTHROPIC_API_KEY) {
  console.error(new MissingApiKeyError().message);
  process.exit(2);
}
const docs = arg(argv, "--docs")?.split(",");
const budgets = arg(argv, "--budgets")?.split(",");
const prefix = mode === "live" ? `evidence/live-eval-${new Date().toISOString().replace(/[:.]/g, "-")}` : `evidence/eval-fixture-${stamp()}`;
const session = sessionRecord(mode, "invoices-v1", { budgets: Object.fromEntries((budgets ?? Object.keys(BUDGETS)).map((b) => [b, BUDGETS[b]])), model: mode === "live" ? process.env.AGENT_MODEL ?? "claude-sonnet-5-5" : "scripted fixture models" });
startEvidence(`${prefix}.jsonl`, session);
const log = new RunLog(`${prefix}.runs.jsonl`);
writeFileSync(`${prefix}.runs.jsonl`, JSON.stringify(session) + "\n");

const { dataset, rows, summaries } = await runEval({ mode, log, docs, budgets });
for (const r of rows) appendFileSync(`${prefix}.jsonl`, JSON.stringify({ type: "doc_score", ...r }) + "\n");
for (const s of summaries) appendFileSync(`${prefix}.jsonl`, JSON.stringify({ type: "summary", ...s }) + "\n");

const get = (b: string, a: string) => summaries.find((s) => s.budget === b && s.architecture === a && s.subset === "all") as Summary | undefined;
const verdicts = Object.keys(BUDGETS)
  .filter((b) => get(b, "two-agent") && get(b, "single-agent"))
  .map((b) => {
    const two = get(b, "two-agent")!;
    const one = get(b, "single-agent")!;
    const d = two.accuracy - one.accuracy;
    const word = Math.abs(d) < 1e-9 ? "the same field accuracy as" : d < 0 ? `LOWER field accuracy (${((-d) * 100).toFixed(1)} points) than` : `higher field accuracy (+${(d * 100).toFixed(1)} points) than`;
    return `- Budget **${b}** (${BUDGETS[b]!.maxModelCalls} model calls per document): two-agent has ${word} the single-agent baseline, using ${(two.calls_per_doc / one.calls_per_doc).toFixed(1)}x the model calls (${two.calls_per_doc.toFixed(1)} vs ${one.calls_per_doc.toFixed(1)} per document).`;
  });

const fixtureNote = mode === "fixture"
  ? `**Fixture mode.** Every number below measures the scripted fixture models in \`src/model/fixtures.ts\`, which read documents with the rules in \`src/model/heuristics.ts\`. Both architectures use the same rules, so accuracy differences come only from orchestration (call budget). Nothing here measures a language model. Tokens and cost are n/a because no API was called.`
  : `**Live mode** with model \`${session.model}\`. Cost is shown only if PRICE_INPUT_PER_MTOK and PRICE_OUTPUT_PER_MTOK were set for this run.`;

const md = [
  `<!-- ${JSON.stringify(session)} -->`,
  `# Baseline vs planner/worker (${mode})`,
  "",
  `Dataset \`${dataset}\`, ${new Set(rows.map((r) => r.doc_id)).size} labelled documents, 9 fields each. Code rev \`${session.code_rev}\`, ${session.node}, ${session.python}. Generated by \`npm run eval${mode === "live" ? " -- --live" : ""}\`.`,
  "",
  fixtureNote,
  "",
  "## Result",
  "",
  ...verdicts,
  "",
  summaryTable(summaries),
  "",
  "Field accuracy counts a correct null (value missing in the gold label and returned as null with a reason) as correct. *missed* = gold has a value but null was returned with a reason. *guessed* = gold is null but a value was returned. *not extracted* = the field was never attempted (budget used up); it counts as wrong. *doc errors flagged* = documents labelled TOTAL_MISMATCH or DUE_BEFORE_INVOICE where the validator raised that code. *rejected calls* = invalid plans, rejected handoff returns and rejected baseline submissions.",
  "",
  "## Held-out documents",
  "",
  "INV-015 and INV-016 were written after the fixture reading rules were frozen. They show what the rules miss on unseen layouts.",
  "",
  heldOutTable(summaries),
  "",
  "## Per document (standard budget)",
  "",
  "| doc | architecture | status | calls | correct | wrong | missed | guessed | not extracted | flagged |",
  "|" + " --- |".repeat(10),
  ...rows.filter((r) => r.budget === "standard").map((r) => {
    const o = Object.values(r.outcomes);
    return `| ${r.doc_id} | ${r.architecture} | ${r.status} | ${r.calls} | ${o.filter((x) => x.startsWith("correct")).length} | ${o.filter((x) => x === "wrong").length} | ${o.filter((x) => x === "missed").length} | ${o.filter((x) => x === "guessed").length} | ${o.filter((x) => x === "not_extracted").length} | ${r.flagged.join(", ") || "-"} |`;
  }),
  "",
].join("\n");
writeFileSync(`${prefix}.md`, md);

console.log(summaryTable(summaries));
console.log("\n" + verdicts.join("\n"));
console.log(`\nreport: ${prefix}.md  scores: ${prefix}.jsonl  run log: ${prefix}.runs.jsonl`);
